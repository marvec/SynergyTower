// Mini-game content for the C64 overlays, generated from the game's own data files (src/data/mg-*.js).
import { JARGON } from '../../src/data/mg-jargon.js';
import { BUZZ_COMMON, BUZZ_DEPT, BINGO_SPEAKERS } from '../../src/data/mg-bingo.js';

/** Greedy word wrap; words longer than `width` are hyphenated. */
export function wrap(text, width) {
  const words = [];
  for (let w of text.split(' ')) {
    while (w.length > width) {
      words.push(w.slice(0, width - 1) + '-');
      w = w.slice(width - 1);
    }
    words.push(w);
  }
  const lines = [''];
  for (const w of words) {
    const cur = lines[lines.length - 1];
    if (!cur) lines[lines.length - 1] = w;
    else if (cur.length + 1 + w.length <= width && !cur.endsWith('-')) lines[lines.length - 1] = cur + ' ' + w;
    else lines.push(w);
  }
  return lines;
}

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

/** Jargon Decoder: buzzword in 2 lines of 30, the honest meaning and 3 decoys of up to 34 chars. */
export function jargonAsm(limit = 16) {
  const fit = JARGON.filter((j) => [j.a, ...j.w].every((s) => s.length <= 34) && wrap(`"${j.p}"`, 30).length <= 2).slice(0, limit);
  const out = ['; generated by c64/build.js from src/data/mg-jargon.js', `J_COUNT = ${fit.length}`];
  out.push(`jargon_lo: .byte ${fit.map((_, i) => `<j${i}`).join(', ')}`);
  out.push(`jargon_hi: .byte ${fit.map((_, i) => `>j${i}`).join(', ')}`);
  fit.forEach((j, i) => {
    const [l1, l2 = ''] = wrap(`"${j.p}"`, 30);
    out.push(`j${i}: .byte ${[l1, l2, j.a, ...j.w].map(str).join(', ')}`);
  });
  return out.join('\n') + '\n';
}

/** Buzzword Bingo: the lobby words + the shared pool, each as the full word and two card lines of up to 11. */
export function bingoAsm(dept = 'lobby') {
  const words = [...BUZZ_DEPT[dept], ...BUZZ_COMMON];
  const out = ['; generated by c64/build.js from src/data/mg-bingo.js', `W_COUNT = ${words.length}`];
  out.push(`words_lo: .byte ${words.map((_, i) => `<w${i}`).join(', ')}`);
  out.push(`words_hi: .byte ${words.map((_, i) => `>w${i}`).join(', ')}`);
  words.forEach((w, i) => {
    const lines = wrap(w, 11);
    if (lines.length > 2) throw new Error(`bingo word too long for a card cell: ${w}`);
    out.push(`w${i}: .byte ${[w, lines[0], lines[1] || ''].map(str).join(', ')}`);
  });
  const speakers = BINGO_SPEAKERS.slice(0, 4);
  speakers.forEach((s, i) => out.push(`speaker${i}: .byte ${str(s)}`));
  out.push(`speakers_lo: .byte ${speakers.map((_, i) => `<speaker${i}`).join(', ')}`);
  out.push(`speakers_hi: .byte ${speakers.map((_, i) => `>speaker${i}`).join(', ')}`);
  out.push(`speakers_len: .byte ${speakers.map((s) => s.length).join(', ')}`);
  return out.join('\n') + '\n';
}

/** HR review (src/data/mg-review.js): question (up to 3 lines of 32), the answer HR wants, 3 honest ones; plus the
 * 40 job titles and 8 department names for the personal question. */
export function reviewAsm({ REVIEW, titles, depts }) {
  const out = ['; generated by c64/build.js from src/data/mg-review.js, departments.js', `R_COUNT = ${REVIEW.length}`];
  out.push(`rev_lo: .byte ${REVIEW.map((_, i) => `<rv${i}`).join(', ')}`);
  out.push(`rev_hi: .byte ${REVIEW.map((_, i) => `>rv${i}`).join(', ')}`);
  REVIEW.forEach((r, i) => {
    const q = wrap(r.q, 32);
    if (q.length > 3) throw new Error(`review question too long: ${r.q}`);
    for (const s of [r.a, ...r.w]) if (s.length > 35) throw new Error(`review answer too long: ${s}`);
    out.push(`rv${i}: .byte ${[q[0], q[1] || '', q[2] || '', r.a, ...r.w].map(str).join(', ')}`);
  });
  titles.forEach((t, i) => out.push(`tt${i}: .byte ${str(t)}`));
  out.push(`ttl_lo: .byte ${titles.map((_, i) => `<tt${i}`).join(', ')}`, `ttl_hi: .byte ${titles.map((_, i) => `>tt${i}`).join(', ')}`);
  depts.forEach((d, i) => out.push(`dp${i}: .byte ${str(d)}`));
  out.push(`dept_lo: .byte ${depts.map((_, i) => `<dp${i}`).join(', ')}`, `dept_hi: .byte ${depts.map((_, i) => `>dp${i}`).join(', ')}`);
  return out.join('\n') + '\n';
}
