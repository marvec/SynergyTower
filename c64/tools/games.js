/** Games in table order: the floors' station games first (as they appear), then the review. */
export function gameList(floorTasks) {
  const ids = [];
  for (const id of floorTasks) if (!ids.includes(id)) ids.push(id);
  for (const id of ids) if (!C64_GAMES[id]) throw new Error(`no C64 entry for game ${id}`);
  ids.push('review');
  return ids.map((id, index) => ({ id, index, name: MINIGAMES[id].name, tier: gameTier(id), file: `mg.${id}`, ...C64_GAMES[id] }));
}

const str = (s) => `.byte ${asc(s).join(', ')}, 0`;

/** gen/games.s: name, help, coffee cost and overlay track/sector per game. `files`: disk name -> { track, sector }. */
export function gamesAsm(list, files, enc = str) {
  const out = ['; generated by c64/build.js (tools/games.js)', `G_COUNT = ${list.length}`, `G_REVIEW = ${list.length - 1}`, `G_LOSTPW = ${list.find((g) => g.id === 'lostpw')?.index ?? 255}`];
  const col = (name, f) => out.push(`${name}: .byte ${list.map(f).join(', ')}`);
  col('game_name_lo', (g) => `<gname${g.index}`);
  col('game_name_hi', (g) => `>gname${g.index}`);
  col('game_help_lo', (g) => `<ghelp${g.index}`);
  col('game_help_hi', (g) => `>ghelp${g.index}`);
  col('game_cost', (g) => (g.id === 'review' ? 2 : g.tier));
  col('game_tier', (g) => g.tier);
  col('game_t', (g) => files[g.file]?.track ?? 0);
  col('game_s', (g) => files[g.file]?.sector ?? 0);
  for (const g of list) out.push(`gname${g.index}: ${enc(g.name)}`); // (ghelpN: in the far texts, gen/far.s)
  return out.join('\n') + '\n';
}
