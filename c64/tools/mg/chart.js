// Magic Chart content for the C64 overlay (src/data/mg-chart.js): the department's chart titles and the labels of
// the mystery controls. A label is printed in the bottom border of its 13-column control box (11 columns).
import { CHART_TITLES, SLIDER_LABELS, KNOB_LABELS, SWITCH_LABELS } from '../../../src/data/mg-chart.js';

const LABEL_MAX = 11;
const TITLE_MAX = 24; // the monitor's title row, left of the slope readout

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const titles = CHART_TITLES[dept] || CHART_TITLES.default;
  for (const t of titles) if (t.length > TITLE_MAX) throw new Error(`chart: title too long: ${t}`);
  const kinds = [SLIDER_LABELS, KNOB_LABELS, SWITCH_LABELS];
  const labels = kinds.flat();
  for (const l of labels) if (l.length > LABEL_MAX) throw new Error(`chart: control label too long: ${l}`);
  const out = ['; generated by c64/build.js from src/data/mg-chart.js (tools/mg/chart.js)'];
  out.push(`T_COUNT = ${titles.length}`);
  out.push(`title_lo: .byte ${titles.map((_, i) => `<ct${i}`).join(', ')}`);
  out.push(`title_hi: .byte ${titles.map((_, i) => `>ct${i}`).join(', ')}`);
  titles.forEach((t, i) => out.push(`ct${i}: .byte ${str(t)}`));
  // labels of all three kinds in one table: slider, knob, switch
  let first = 0;
  out.push(`kind_first: .byte ${kinds.map((k) => ((first += k.length), first - k.length)).join(', ')}`);
  out.push(`kind_count: .byte ${kinds.map((k) => k.length).join(', ')}`);
  out.push(`lab_lo: .byte ${labels.map((_, i) => `<cb${i}`).join(', ')}`);
  out.push(`lab_hi: .byte ${labels.map((_, i) => `>cb${i}`).join(', ')}`);
  out.push(`lab_len: .byte ${labels.map((l) => l.length).join(', ')}`);
  labels.forEach((l, i) => out.push(`cb${i}: .byte ${str(l)}`));
  return out.join('\n') + '\n';
}
