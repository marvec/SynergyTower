// Fix the Spreadsheet (src/minigames/spreadsheet.js) content for the C64 overlay: the department's 10 row labels
// (the JS keeps them in the game module, LABELS, with 'default' for the lobby) and the error codes.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = fileURLToPath(new URL('../../../src/minigames/spreadsheet.js', import.meta.url));
const LABEL_W = 11; // columns 2-12 of a row

/** The module doesn't export its tables: evaluate the `const NAME = ...;` literal from the source. */
function constant(src, name) {
  const at = src.indexOf(`const ${name} = `);
  if (at < 0) throw new Error(`spreadsheet: no ${name} in the JS`);
  const end = src.indexOf(';\n', at);
  return new Function(`return ${src.slice(at + name.length + 9, end)}`)();
}

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const src = readFileSync(SRC, 'utf8');
  const LABELS = constant(src, 'LABELS');
  const ERRORS = constant(src, 'ERRORS');
  const labels = LABELS[dept] || LABELS.default;
  if (labels.length !== 10) throw new Error('spreadsheet: expected 10 labels');
  for (const l of labels) if (l.length > LABEL_W) throw new Error(`spreadsheet label too long: ${l}`);
  for (const e of ERRORS) if (e.length > 7) throw new Error(`spreadsheet error code too long: ${e}`);
  const out = ['; generated by c64/build.js (tools/mg/spreadsheet.js) from src/minigames/spreadsheet.js', `LABEL_N = ${labels.length}`, `ERR_N = ${ERRORS.length}`];
  out.push(`label_lo: .byte ${labels.map((_, i) => `<lbl${i}`).join(', ')}`);
  out.push(`label_hi: .byte ${labels.map((_, i) => `>lbl${i}`).join(', ')}`);
  labels.forEach((l, i) => out.push(`lbl${i}: .byte ${str(l)}`));
  out.push(`err_lo: .byte ${ERRORS.map((_, i) => `<err${i}`).join(', ')}`);
  out.push(`err_hi: .byte ${ERRORS.map((_, i) => `>err${i}`).join(', ')}`);
  ERRORS.forEach((l, i) => out.push(`err${i}: .byte ${str(l)}`));
  return out.join('\n') + '\n';
}
