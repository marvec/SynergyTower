// Write the Email content for the C64 overlay (mg_compose.s), from src/data/mg-compose.js: the department's
// sentences, then the general ones (each: text before the blank, text after it, the right phrase, 3 wrong ones),
// and the department's subject line.
import { COMPOSE, SUBJECTS } from '../../../src/data/mg-compose.js';

const OPT_MAX = 15; // an option box: 19 columns = frame, number, space, 15 characters, frame
const LINE_W = 36; // the email body: columns 2-37
const SUBJ_MAX = 28; // "Subject: " + this inside the window

const ascii = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return s;
};
// ca65 string bytes, 0-terminated (quotes as 34, no empty "" literals)
const str = (s) => [...ascii(s).split('"').flatMap((part, i) => [...(i ? ['34'] : []), ...(part ? [`"${part}"`] : [])]), '0'].join(', ');

/** Lines the overlay's wrap gives (break at the last space at or before LINE_W). */
function lines(s) {
  const out = [];
  while (s.length > LINE_W) {
    const k = s.lastIndexOf(' ', LINE_W);
    if (k <= 0) throw new Error(`compose: no break in "${s}"`);
    out.push(s.slice(0, k));
    s = s.slice(k + 1);
  }
  return [...out, s];
}

export function dataAsm({ dept = 'lobby' } = {}) {
  const deptPool = COMPOSE[dept] || [];
  const items = [...deptPool, ...COMPOSE.general];
  const out = ['; generated by c64/build.js from src/data/mg-compose.js (tools/mg/compose.js)'];
  out.push(`D_COUNT = ${deptPool.length}`, `G_COUNT = ${COMPOSE.general.length}`, `I_COUNT = ${items.length}`);
  items.forEach((it, i) => {
    const parts = it.t.split('___');
    if (parts.length !== 2) throw new Error(`compose: one blank expected in "${it.t}"`);
    for (const o of [it.a, ...it.w]) {
      if (o.length > OPT_MAX) throw new Error(`compose: option too long for its box: ${o}`);
      // the "_____" blank and every phrase must leave the sentence on at most 2 lines
      for (const f of [o, '_____']) if (lines(parts[0] + f + parts[1]).length > 2) throw new Error(`compose: more than 2 lines: ${it.t} / ${f}`);
    }
    if (it.w.length !== 3) throw new Error(`compose: 3 wrong phrases expected: ${it.t}`);
    out.push(`ci${i}: .byte ${[parts[0], parts[1], it.a, ...it.w].map(str).join(', ')}`);
  });
  out.push(`item_lo: .byte ${items.map((_, i) => `<ci${i}`).join(', ')}`);
  out.push(`item_hi: .byte ${items.map((_, i) => `>ci${i}`).join(', ')}`);
  const subject = SUBJECTS[dept] || SUBJECTS.default;
  if (subject.length > SUBJ_MAX) throw new Error(`compose: subject too long: ${subject}`);
  out.push(`s_subject: .byte ${str(subject)}`);
  return out.join('\n') + '\n';
}
