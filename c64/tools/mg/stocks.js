// Quarterly Ticker (src/minigames/stocks.js) content for the C64 overlay: the ticker symbols (a local constant
// of the module, read from its source; the finance floor always trades SYNG) and a sine table for the price.
import { readFileSync } from 'node:fs';

const SRC = readFileSync(new URL('../../../src/minigames/stocks.js', import.meta.url), 'utf8');
const TICKERS = new Function(`return ${SRC.match(/const TICKERS = (\[[^\]]*\]);/)[1]}`)();
const TICKER_W = 4; // printed in a 4-character field

export function dataAsm({ dept = 'lobby' } = {}) {
  for (const t of TICKERS) if (!/^[A-Z]{1,4}$/.test(t)) throw new Error(`stocks: ticker must be 1-4 capitals: ${t}`);
  if (!TICKERS.includes('SYNG')) throw new Error('stocks: no SYNG ticker for finance');
  const pad = (t) => t.padEnd(TICKER_W, ' ');
  const out = ['; generated by c64/build.js (tools/mg/stocks.js) from src/minigames/stocks.js'];
  out.push(`T_COUNT = ${TICKERS.length}`, `T_FIXED = ${dept === 'finance' ? TICKERS.indexOf('SYNG') : 255}   ; finance: always SYNG`);
  out.push(`tickers: .byte ${TICKERS.map((t) => `"${pad(t)}"`).join(', ')}   ; ${TICKER_W} chars each`);
  out.push(`sin_tab: .byte ${Array.from({ length: 256 }, (_, i) => (Math.round(127 * Math.sin((2 * Math.PI * i) / 256)) + 256) & 255).join(', ')}`);
  return out.join('\n') + '\n';
}
