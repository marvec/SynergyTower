// Fridge Tetris (src/minigames/fridge.js) content for the C64 overlay, from src/data/mg-fridge.js: the sticky
// notes (the shared pool + the department's) wrapped for the fridge door, the container names wrapped for the
// NEXT panel, and the shelf-cleared lines.
import { FRIDGE_NOTES, FRIDGE_NOTES_DEPT, TUPPERWARE, MYSTERY, ITEM_NAMES, CLEAR_LINES } from '../../../src/data/mg-fridge.js';
import { wrap } from '../mgdata.js';

const NOTE_W = 11; // door note: 11 chars × 6 lines
const NOTE_H = 6;
const NAME_W = 11; // NEXT panel: 11 chars × 2 lines

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

/** wrap(), keeping a " - " with the word after it ("- KAREN", "- Mgmt"). */
const wrapDash = (s, w) => wrap(s.replaceAll(' - ', ' \u0000'), w).map((x) => x.replaceAll('\u0000', '- '));

/** Pointer table + strings; each entry is several 0-terminated lines. */
function table(out, name, entries) {
  out.push(`${name}_lo: .byte ${entries.map((_, i) => `<${name}${i}`).join(', ')}`);
  out.push(`${name}_hi: .byte ${entries.map((_, i) => `>${name}${i}`).join(', ')}`);
  entries.forEach((lines, i) => out.push(`${name}${i}: .byte ${lines.map(str).join(', ')}`));
}

export function dataAsm({ dept = 'lobby' } = {}) {
  const notes = [...FRIDGE_NOTES, ...(FRIDGE_NOTES_DEPT[dept] || [])].map((n) => {
    const l = wrapDash(n, NOTE_W);
    if (l.length > NOTE_H) throw new Error(`fridge note too long for the door: ${n}`);
    return [...l, '']; // an empty line ends the note
  });
  // names: TUPPERWARE, then MYSTERY, then yogurt, milk, cake (the piece kinds' order in mg_fridge.s)
  const names = [...TUPPERWARE, ...MYSTERY, ITEM_NAMES.yogurt, ITEM_NAMES.milk, ITEM_NAMES.cake].map((n) => {
    const l = wrapDash(n, NAME_W);
    if (l.length > 2) throw new Error(`fridge name too long for the NEXT panel: ${n}`);
    return [l[0], l[1] || ''];
  });
  for (const s of CLEAR_LINES) if (s.length > 18) throw new Error(`fridge line too long: ${s}`);
  const out = ['; generated by c64/build.js (tools/mg/fridge.js) from src/data/mg-fridge.js'];
  out.push(`NOTE_N = ${notes.length}`, `TUP_N = ${TUPPERWARE.length}`, `MYST_N = ${MYSTERY.length}`, `NAME_YOGURT = ${TUPPERWARE.length + MYSTERY.length}`);
  out.push(`CLEAR_N = ${CLEAR_LINES.length}`);
  table(out, 'note', notes);
  table(out, 'name', names);
  table(out, 'clr', CLEAR_LINES.map((s) => [s]));
  return out.join('\n') + '\n';
}
