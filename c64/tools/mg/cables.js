// Cable Spaghetti content for the C64 overlay (src/data/mg-cables.js): the department's device labels, the
// generic pool and the "it clicked" lines. A label sits in a 14-column slot of the socket box, so longer
// generic labels are left out.
import { DEVICES_GENERIC, DEVICES_DEPT, CONNECT_LINES } from '../../../src/data/mg-cables.js';

const LABEL_MAX = 14;

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const own = DEVICES_DEPT[dept] || [];
  for (const d of own) if (d.length > LABEL_MAX) throw new Error(`cables: device label too long: ${d}`);
  const generic = DEVICES_GENERIC.filter((d) => d.length <= LABEL_MAX);
  if (generic.length < 12) throw new Error('cables: fewer than 12 generic labels fit');
  const devices = [...own, ...generic];
  const out = ['; generated by c64/build.js from src/data/mg-cables.js (tools/mg/cables.js)'];
  out.push(`D_DEPT = ${own.length}`, `D_GEN = ${generic.length}`);
  out.push(`dev_lo: .byte ${devices.map((_, i) => `<dv${i}`).join(', ')}`);
  out.push(`dev_hi: .byte ${devices.map((_, i) => `>dv${i}`).join(', ')}`);
  devices.forEach((d, i) => out.push(`dv${i}: .byte ${str(d)}`));
  out.push(`CL_COUNT = ${CONNECT_LINES.length}`);
  out.push(`cl_lo: .byte ${CONNECT_LINES.map((_, i) => `<cl${i}`).join(', ')}`);
  out.push(`cl_hi: .byte ${CONNECT_LINES.map((_, i) => `>cl${i}`).join(', ')}`);
  out.push(`cl_len: .byte ${CONNECT_LINES.map((s) => s.length).join(', ')}`);
  CONNECT_LINES.forEach((s, i) => out.push(`cl${i}: .byte ${str(s)}`));
  return out.join('\n') + '\n';
}
