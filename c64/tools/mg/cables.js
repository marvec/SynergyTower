// Cable Spaghetti content for the C64 overlay (src/data/mg-cables.js): the department's device labels, the
// generic pool, the PROD socket's label and the "it clicked" lines. A label sits in a 16-column slot of the
// socket box, so longer labels are left out (generic: 'Server (unlabeled)'; marketing: 'Influencer ring light').
import { DEVICES_GENERIC, DEVICES_DEPT, PROD_DEVICE, CONNECT_LINES } from '../../../src/data/mg-cables.js';

const LABEL_MAX = 16;
const LINE_MAX = 22; // the message slot on row 23

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const own = (DEVICES_DEPT[dept] || []).filter((d) => d.length <= LABEL_MAX);
  const generic = DEVICES_GENERIC.filter((d) => d.length <= LABEL_MAX);
  if (generic.length < 12) throw new Error('cables: fewer than 12 generic labels fit');
  // 'Prod DB - DO NOT TOUCH' -> 'Prod DB NO TOUCH'
  const [what, warn = ''] = PROD_DEVICE.split(' - ');
  const prod = PROD_DEVICE.length <= LABEL_MAX ? PROD_DEVICE : `${what} ${warn.replace('DO NOT', 'NO')}`.trim();
  if (prod.length > LABEL_MAX) throw new Error(`cables: PROD label too long: ${prod}`);
  for (const s of CONNECT_LINES) if (s.length > LINE_MAX) throw new Error(`cables: line too long: ${s}`);
  const devices = [...own, ...generic];
  const out = ['; generated by c64/build.js from src/data/mg-cables.js (tools/mg/cables.js)'];
  out.push(`D_DEPT = ${own.length}`, `D_GEN = ${generic.length}`);
  out.push(`dev_lo: .byte ${devices.map((_, i) => `<dv${i}`).join(', ')}, <dv_prod`);
  out.push(`dev_hi: .byte ${devices.map((_, i) => `>dv${i}`).join(', ')}, >dv_prod`);
  out.push(`D_PROD = ${devices.length}`);
  devices.forEach((d, i) => out.push(`dv${i}: .byte ${str(d)}`));
  out.push(`dv_prod: .byte ${str(prod)}`);
  out.push(`CL_COUNT = ${CONNECT_LINES.length}`);
  out.push(`cl_lo: .byte ${CONNECT_LINES.map((_, i) => `<cl${i}`).join(', ')}`);
  out.push(`cl_hi: .byte ${CONNECT_LINES.map((_, i) => `>cl${i}`).join(', ')}`);
  CONNECT_LINES.forEach((s, i) => out.push(`cl${i}: .byte ${str(s)}`));
  return out.join('\n') + '\n';
}
