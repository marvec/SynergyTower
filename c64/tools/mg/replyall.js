// Reply-All Apocalypse content for the C64 overlay (src/data/mg-replyall.js -> build/gen/mg_replyall_data.s): the
// department's thread topics, the reply-all snippets, senders, the important (starred) mails, the oops lines and the
// trash-can sprite.
import { TOPICS, REPLIES, SENDERS, VIPS, OOPS } from '../../../src/data/mg-replyall.js';

// VIP sender colours on the C64 (hires colours 0-7): CEO red, HR purple, client green, boss cyan (blue is too dark
// on black).
const VIP_COLOR = { CEO: 2, 'HR Team': 4, Client: 5, 'Your Boss': 3 };

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  // a quote inside the text becomes byte 34 (no empty "" pieces: ca65 rejects them)
  const parts = s.split('"').flatMap((p, i) => [...(i ? ['34'] : []), ...(p ? [`"${p}"`] : [])]);
  return [...parts, '0'].join(', ');
};

// Multicolour sprite (12 fat pixels per row): X = sprite colour, O = $d025 (black).
const TRASH = ['.XXX........', 'XXXXX.......', 'XOXOX.......', 'XOXOX.......', 'XOXOX.......', 'XOXOX.......', 'XXXXX.......'];

export function dataAsm({ dept }) {
  const topics = TOPICS[dept] || TOPICS.default;
  const out = ['; generated by c64/build.js from src/data/mg-replyall.js (tools/mg/replyall.js)'];
  const table = (name, list, check) => {
    out.push(`${name.toUpperCase()}_COUNT = ${list.length}`);
    list.forEach((s, i) => {
      check?.(s);
      out.push(`${name}${i}: .byte ${str(s)}`);
    });
    out.push(`${name}_lo: .byte ${list.map((_, i) => `<${name}${i}`).join(', ')}`);
    out.push(`${name}_hi: .byte ${list.map((_, i) => `>${name}${i}`).join(', ')}`);
  };
  table('topic', topics, (s) => {
    if (s.length + 10 > 38) throw new Error(`topic too long for the thread line: ${s}`);
  });
  table('reply', REPLIES);
  table('sender', SENDERS);
  table('vsender', VIPS.map((v) => v.sender));
  out.push(`vip_color: .byte ${VIPS.map((v) => VIP_COLOR[v.sender] ?? 7).join(', ')}`);
  if (VIPS.some((v) => v.subjects.length !== 3)) throw new Error('every VIP needs 3 subjects');
  table('subject', VIPS.flatMap((v) => v.subjects), (s) => {
    if (s.length > 19) throw new Error(`VIP subject longer than 19: ${s}`);
  });
  table('oops', OOPS, (s) => {
    if (s.length > 38) throw new Error(`oops line too long: ${s}`);
  });
  const bytes = [];
  for (let r = 0; r < 21; r++) {
    const line = TRASH[r] ?? '............';
    for (let b = 0; b < 3; b++) bytes.push([...line.slice(b * 4, b * 4 + 4)].reduce((v, ch) => (v << 2) | '.OX'.indexOf(ch), 0));
  }
  out.push(`trash_spr: .byte ${bytes.join(', ')}`);
  return out.join('\n') + '\n';
}
