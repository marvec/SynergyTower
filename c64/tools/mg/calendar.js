// Schedule the Meeting content for the C64 overlay (src/mg_calendar.s): the department's attendees and the busy
// labels. The JS game keeps them as module constants in src/minigames/calendar.js (not exported), so they are read
// from its source, like build.js reads the terminal's COMMANDS.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(import.meta.dir, '../../../src/minigames/calendar.js'), 'utf8');

/** The literal after `const NAME =` up to its closing `;` at the end of a line, evaluated. */
const constant = (name) => {
  const at = SRC.indexOf(`const ${name} = `);
  if (at < 0) throw new Error(`calendar.js: no const ${name}`);
  return new Function(`return ${SRC.slice(at + name.length + 9, SRC.indexOf(';\n', at))}`)();
};

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

const table = (out, label, items) => {
  items.forEach((s, i) => out.push(`${label}${i}: .byte ${str(s)}`));
  out.push(`${label}_lo: .byte ${items.map((_, i) => `<${label}${i}`).join(', ')}`);
  out.push(`${label}_hi: .byte ${items.map((_, i) => `>${label}${i}`).join(', ')}`);
  out.push(`${label}_len: .byte ${items.map((s) => s.length).join(', ')}`);
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const PEOPLE = constant('PEOPLE');
  const LABELS = constant('BUSY_LABELS');
  const names = PEOPLE[dept] || PEOPLE.default;
  for (const n of names) if (n.length > 14) throw new Error(`calendar attendee name too long: ${n}`);
  const out = ['; generated by c64/build.js (tools/mg/calendar.js) from src/minigames/calendar.js', `P_NAMES = ${names.length}`, `B_LABELS = ${LABELS.length}`];
  table(out, 'pn', names);
  table(out, 'bl', LABELS);
  return out.join('\n') + '\n';
}
