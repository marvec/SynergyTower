// Slide Deck Order content for the C64 overlay (src/data/mg-order.js): the department's decks, each a title
// and its steps in order. A step is shown in two ways: in a choice box (one line of up to OPT_W) and on its
// slide once placed (up to two lines of SLIDE_W), so both forms are generated here.
import { SEQUENCES } from '../../../src/data/mg-order.js';
import { wrap } from '../mgdata.js';

const TITLE_MAX = 32; // "Deck: " + title, centred on row 2
const OPT_W = 18;
const SLIDE_W = 15;
const MAX_STEPS = 6; // round(byDiff(1, 4, 6))

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const decks = SEQUENCES[dept] || SEQUENCES.it;
  const out = ['; generated by c64/build.js from src/data/mg-order.js (tools/mg/order.js)', `D_COUNT = ${decks.length}`];
  out.push(`deck_lo: .byte ${decks.map((_, i) => `<dk${i}`).join(', ')}`);
  out.push(`deck_hi: .byte ${decks.map((_, i) => `>dk${i}`).join(', ')}`);
  // per deck: title, step count, then per step: option line, slide line 1, slide line 2 ("" if one line)
  decks.forEach(([title, ...steps], i) => {
    if (title.length > TITLE_MAX) throw new Error(`order: deck title too long: ${title}`);
    steps = steps.slice(0, MAX_STEPS);
    const parts = [str(title), String(steps.length)];
    for (const s of steps) {
      if (s.length > OPT_W) throw new Error(`order: step too long for a choice box: ${s}`);
      const lines = wrap(s, SLIDE_W);
      if (lines.length > 2 || lines.some((l) => l.endsWith('-'))) throw new Error(`order: step does not fit a slide: ${s}`);
      parts.push(str(s), str(lines[0]), str(lines[1] || ''));
    }
    out.push(`dk${i}: .byte ${parts.join(', ')}`);
  });
  return out.join('\n') + '\n';
}
