// Coffee Run content for the C64 overlay (src/c64/mg_coffee.s): the order parts and options, the colleagues' names,
// the department boss and the cup heights. The JS game keeps them as module constants in src/minigames/coffee.js
// (not exported), so they are read from its source, like build.js reads the terminal's COMMANDS.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(import.meta.dir, '../../../src/minigames/coffee.js'), 'utf8');

/** The literal after `const NAME =` up to its closing `;` at the end of a line, evaluated. */
const constant = (name) => {
  const at = SRC.indexOf(`const ${name} = `);
  if (at < 0) throw new Error(`coffee.js: no const ${name}`);
  const end = SRC.indexOf(';\n', at);
  return new Function(`return ${SRC.slice(at + name.length + 9, end)}`)();
};

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

const table = (out, label, items) => {
  items.forEach((s, i) => out.push(`${label}${i}: .byte ${str(s)}`));
  out.push(`${label}_lo: .byte ${items.map((_, i) => `<${label}${i}`).join(', ')}`);
  out.push(`${label}_hi: .byte ${items.map((_, i) => `>${label}${i}`).join(', ')}`);
};

export function dataAsm({ dept = 'lobby' } = {}) {
  // floors 1-2 (difficulty up to 0.17): round(byDiff(d, 2, 4)) = 2 parts per order, size and drink
  const PARTS = constant('PARTS').slice(0, 2);
  const NAMES = constant('NAMES');
  const BOSSES = constant('BOSSES');
  const CUP = constant('CUP');
  const out = ['; generated by c64/build.js (tools/mg/coffee.js) from src/minigames/coffee.js', `N_COUNT = ${NAMES.length}`];
  for (const p of PARTS) for (const o of p.options) if (o.length > 20) throw new Error(`coffee option too long: ${o}`);
  // every option of every part in one table; part k's options start at part_first[k]
  const opts = PARTS.flatMap((p) => p.options);
  out.push(`part_first: .byte ${PARTS.map((_, k) => PARTS.slice(0, k).reduce((n, p) => n + p.options.length, 0)).join(', ')}`);
  out.push(`part_count: .byte ${PARTS.map((p) => p.options.length).join(', ')}`);
  table(out, 'part', PARTS.map((p) => p.key));
  table(out, 'opt', opts);
  table(out, 'nm', NAMES);
  out.push(`s_boss: .byte ${str(BOSSES[dept] ?? NAMES[0])}`);
  // cup height in rows (1 row = 4 JS pixels, drawn 2× in the JS game) per size, and with no size picked yet
  out.push(`cup_rows: .byte ${PARTS[0].options.map((o) => Math.floor(CUP[o] / 4)).join(', ')}`);
  out.push(`CUP_DEFAULT = ${Math.floor(16 / 4)}`);
  return out.join('\n') + '\n';
}
