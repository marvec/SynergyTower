// Rapid Reply content for the C64 overlay (build/gen/mg_typing_data.s): the department's phrases + the general ones
// (src/minigames/typing.js `const PHRASES`, read from the module's source since it is not exported), their lengths,
// which are short (<= 22 chars, the pool below d 0.5) and the accuracy curve acc^1.5 of the score as a table.
import { readFileSync } from 'node:fs';

const SRC = new URL('../../../src/minigames/typing.js', import.meta.url);
const PHRASE_W = 36; // the input line: columns 2-37
const MAX_PICK = 5; // round(byDiff(d, 3, 5))

function phrases() {
  const src = readFileSync(SRC, 'utf8');
  const a = src.indexOf('const PHRASES = ');
  const b = src.indexOf('\n};\n', a);
  if (a < 0 || b < 0) throw new Error('typing: PHRASES not found in src/minigames/typing.js');
  return new Function(`return ${src.slice(a + 16, b + 2)}`)();
}

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  if (/[^a-z ',]/.test(s)) throw new Error(`typing: no C64 key mapping for a character in "${s}"`);
  const parts = s.split('"').flatMap((p, i) => [...(i ? ['34'] : []), ...(p ? [`"${p}"`] : [])]);
  return [...parts, '0'].join(', ');
};

export function dataAsm({ dept }) {
  const all = phrases();
  const pool = [...(all[dept] || []), ...all.general];
  const out = ['; generated by c64/build.js from src/minigames/typing.js PHRASES (tools/mg/typing.js)'];
  for (const p of pool) if (p.length > PHRASE_W) throw new Error(`typing: phrase too long: ${p}`);
  const longest = pool.map((p) => p.length).sort((a, b) => b - a).slice(0, MAX_PICK).reduce((s, n) => s + n, 0);
  if (longest > 255) throw new Error('typing: total characters must stay below 256');
  out.push(`P_COUNT = ${pool.length}`, `P_SHORT = ${pool.filter((p) => p.length <= 22).length}`);
  pool.forEach((p, i) => out.push(`ph${i}: .byte ${str(p)}`));
  out.push(`ph_lo: .byte ${pool.map((_, i) => `<ph${i}`).join(', ')}`);
  out.push(`ph_hi: .byte ${pool.map((_, i) => `>ph${i}`).join(', ')}`);
  out.push(`ph_len: .byte ${pool.map((p) => p.length).join(', ')}`);
  out.push(`ph_short: .byte ${pool.map((p) => (p.length <= 22 ? 1 : 0)).join(', ')}`);
  const pow = Array.from({ length: 256 }, (_, a) => Math.round(255 * (a / 255) ** 1.5));
  for (let k = 0; k < 256; k += 32) out.push(`${k ? '        ' : 'pow15:  '} .byte ${pow.slice(k, k + 32).join(', ')}`);
  return out.join('\n') + '\n';
}
