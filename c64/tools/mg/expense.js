// Expense Fraud Detective content for the C64 overlay (src/data/mg-expense.js -> build/gen/mg_expense_data.s):
// the receipts of the floor's department and the shared ones, legit first, plus submitters, verdict lines and the
// rubber-stamp sprite shapes.
import { RECEIPTS, SUBMITTERS, RIGHT_LINES, WRONG_LINES } from '../../../src/data/mg-expense.js';
import { wrap } from '../mgdata.js';

const DAYS = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const INNER = 28; // receipt text width (screen columns 6-33)

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  // a quote inside the text becomes byte 34 (no empty "" pieces: ca65 rejects them)
  const parts = s.split('"').flatMap((p, i) => [...(i ? ['34'] : []), ...(p ? [`"${p}"`] : [])]);
  return [...parts, '0'].join(', ');
};
const money = (n) => {
  const [a, b] = n.toFixed(2).split('.');
  return a.replace(/\B(?=(\d{3})+(?!\d))/g, ',') + '.' + b;
};

// Multicolour sprite rows (12 fat pixels): O = $d025 (black outline), X = sprite colour, H = $d026 (light red).
const STAMP = {
  knob: ['....OOOO....', '....OHXO....', '....OXXO....', '....OOOO....'],
  stem: ['.....XX.....', '.....XX.....', '.....XX.....'],
  body: ['.OOOOOOOOOO.', '.OHHHHHHHHO.', '.OXXXXXXXXO.', '.OXXXXXXXXO.', '.OOOOOOOOOO.'],
  rubber: ['OOOOOOOOOOOO', 'OXXXXXXXXXXO', 'OXXXXXXXXXXO', 'OOOOOOOOOOOO'],
};
const STAMP_ROWS = 16; // two char rows

/** Each stamp part in its own sprite, at its height within the 13 stamp rows (3 bytes per row). */
function spriteRows() {
  const out = [];
  let y = 0;
  for (const [name, art] of Object.entries(STAMP)) {
    const bytes = [];
    for (let r = 0; r < STAMP_ROWS; r++) {
      const line = art[r - y] ?? '............';
      for (let b = 0; b < 3; b++) bytes.push([...line.slice(b * 4, b * 4 + 4)].reduce((v, ch) => (v << 2) | '.OXH'.indexOf(ch), 0));
    }
    y += art.length;
    out.push(`stamp_${name}: .byte ${bytes.join(', ')}`);
  }
  return out;
}

export function dataAsm({ dept }) {
  const pool = RECEIPTS.filter((r) => !r.dept || r.dept === dept);
  const legit = pool.filter((r) => !r.fraud);
  const fraud = pool.filter((r) => r.fraud);
  const all = [...legit, ...fraud];
  const out = ['; generated by c64/build.js from src/data/mg-expense.js (tools/mg/expense.js)'];
  out.push(`R_COUNT = ${all.length}`, `R_LEGIT = ${legit.length}`, `R_FRAUD = ${fraud.length}`, `STAMP_ROWS = ${STAMP_ROWS}`);
  out.push(`rec_lo: .byte ${all.map((_, i) => `<rc${i}`).join(', ')}`);
  out.push(`rec_hi: .byte ${all.map((_, i) => `>rc${i}`).join(', ')}`);
  all.forEach((r, i) => {
    // flags: bit 7 fraud, bit 6 the department's own (weight 3 vs 1.2), bit 3 two item lines, bits 0-2 forced day + 1
    const day = r.day ? DAYS.indexOf(r.day) + 1 : 0;
    if (r.day && day === 0) throw new Error(`bad day ${r.day}`);
    if (r.lines.length < 1 || r.lines.length > 2) throw new Error(`receipt needs 1-2 lines: ${r.merchant}`);
    const flags = (r.fraud ? 0x80 : 0) | (r.dept === dept ? 0x40 : 0) | (r.lines.length === 2 ? 8 : 0) | day;
    const sum = r.lines.reduce((s, [, a]) => s + a, 0);
    const reason = wrap('Reason: ' + r.reason, INNER);
    const tell = wrap(r.tell, 38);
    if (reason.length > 2) throw new Error(`reason too long: ${r.reason}`);
    if (tell.length > 2) throw new Error(`tell too long: ${r.tell}`);
    if (r.merchant.length > INNER) throw new Error(`merchant too long: ${r.merchant}`);
    const items = r.lines.flatMap(([t, a]) => {
      if (t.length + 1 + money(a).length > INNER) throw new Error(`item line too long: ${t}`);
      return [t, money(a)];
    });
    const strings = [r.merchant, ...items, money(sum), reason[0], reason[1] || '', tell[0], tell[1] || ''];
    out.push(`rc${i}: .byte ${flags}, ${strings.map(str).join(', ')}`);
  });
  const table = (name, list) => {
    list.forEach((s, i) => out.push(`${name}${i}: .byte ${str(s)}`));
    out.push(`${name}_lo: .byte ${list.map((_, i) => `<${name}${i}`).join(', ')}`);
    out.push(`${name}_hi: .byte ${list.map((_, i) => `>${name}${i}`).join(', ')}`);
  };
  out.push(`SUB_COUNT = ${SUBMITTERS.length}`, `RIGHT_COUNT = ${RIGHT_LINES.length}`, `WRONG_COUNT = ${WRONG_LINES.length}`);
  table('sub', SUBMITTERS.map((s) => '- ' + s));
  table('rl', RIGHT_LINES);
  table('wl', WRONG_LINES);
  out.push(`day_names: .byte "${DAYS.join('')}"`, `month_names: .byte "${MONTHS.join('')}"`);
  out.push(...spriteRows());
  return out.join('\n') + '\n';
}
