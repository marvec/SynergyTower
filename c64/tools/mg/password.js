// Password Policy (src/minigames/password.js) content for the C64 overlay (mg_password.s).
// The policies themselves come from the JS generator (generatePolicy, with its own seeded RNG), made at build time:
// the C64 has no room for the search with its reference solutions. For each of the 7 difficulty bands in which the
// JS policy shape changes (rule count round(4 + 4d), min length round(6 + 2d), mid-tier rules round(1 + 2d)) there
// are POLICIES policies; the overlay picks one at random. A policy keeps its rules (ids), the numbers in their texts,
// the chunk tiles each rule unlocks (as create() deals them) and, in test builds, the reference solution for the bot.
// Rule texts are shortened to fit a 36-column row; $01-$06 in a text are filled in from the policy.
import { generatePolicy } from '../../../src/minigames/password.js';
import { FRUITS, MONTHS, COFFEE, ANIMALS, VALUES, DEPT_WORDS, IT_QUIPS, DONE_LINES, SCREEN_TITLES } from '../../../src/data/mg-password.js';
import { createRng, hashString } from '../../../src/core/rng.js';
import { wrap } from '../mgdata.js';

const POLICIES = 5;
const BOT_POLICIES = 3;
// Difficulty bands: MG_DIFF from which each band starts, and the d its policies are made with.
const BANDS = [0, 32, 64, 96, 160, 192, 224];
const BAND_D = [0.06, 0.19, 0.31, 0.5, 0.69, 0.81, 0.94];
const RULE_W = 36;
const ROMANS = [[4, 'IV'], [6, 'VI'], [9, 'IX'], [11, 'XI'], [14, 'XIV'], [40, 'XL']]; // as in password.js

// Rule ids in the overlay's order (its check table) with their C64 texts. $01 min length, $02 max length,
// $03 digit sum, $04 floor, $05 quarter digit, $06 Roman number.
const RULES = [
  ['len', 'Between \x01 and \x02 characters.'],
  ['digit', 'Must contain a digit.'],
  ['upper', 'Must contain an uppercase letter.'],
  ['special', 'Must contain a special: ! ? # % & *'],
  ['lower', 'Needs lowercase too. Stop shouting.'],
  ['nopass', "Must not contain 'password'."],
  ['no123', "No '123'. Hackers know that one."],
  ['sum', 'Digits must sum to \x03. Ask Finance.'],
  ['month', 'Must include a month (jan, feb...).'],
  ['fruit', 'Needs a fruit. IT is on a diet.'],
  ['floor', 'Must include our floor number (\x04).'],
  ['quarter', 'Must mention this quarter: Q\x05.'],
  ['bang', "Must end with '!'. Be enthusiastic."],
  ['start', 'Must start with a capital letter.'],
  ['triple', 'No 3 identical characters in a row.'],
  ['nozero', 'No zeros. Gary reads them as O.'],
  ['even', 'Length must be an even number.'],
  ['coffee', 'Coffee size: tall, grande or venti.'],
  ['dept', null], // per department, below
  ['caps3', '3+ capital letters. Be assertive.'],
  ['value', 'Value in CAPS: TRUST, BOLD or AGILE.'],
  ['synergy', 'Add SYNERGY. In caps. We mean it.'],
  ['roman', 'Include the Roman numeral for \x06.'],
  ['noe', 'The letter E is on vacation. No E!'],
  ['prime', 'Length must be a prime number.'],
  ['len14', 'Actually: at least 14 characters.'],
  ['animal', 'An animal sound (moo, oink, baa...).'],
];
const ID = Object.fromEntries(RULES.map(([id], i) => [id, i]));

const ascii = (s) => {
  if (/[^\x01-\x06\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return s;
};
/** ca65 bytes of a 0-terminated string (quotes and the $01-$06 codes as numbers). */
const str = (s) => {
  const out = [];
  let lit = '';
  for (const ch of ascii(s)) {
    if (ch === '"' || ch < ' ') {
      if (lit) out.push(`"${lit}"`), (lit = '');
      out.push(String(ch.charCodeAt(0)));
    } else lit += ch;
  }
  if (lit) out.push(`"${lit}"`);
  out.push('0');
  return out.join(', ');
};
const table = (out, name, items, emit) => {
  items.forEach((it, i) => out.push(`${name}${i}: .byte ${emit(it)}`));
  out.push(`${name}_lo: .byte ${items.map((_, i) => `<${name}${i}`).join(', ')}`);
  out.push(`${name}_hi: .byte ${items.map((_, i) => `>${name}${i}`).join(', ')}`);
};
/** Status texts: two lines of up to 40. */
const two = (s) => {
  const l = wrap(s, 40);
  if (l.length > 2) throw new Error(`password: status too long: ${s}`);
  return [l[0], l[1] || ''];
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const [word, punch] = DEPT_WORDS[dept] || DEPT_WORDS.it;
  const texts = RULES.map(([id, t]) => (id === 'dept' ? `Add ${word}. ${punch}` : t));
  for (const t of texts) if (t.replace(/[\x01-\x06]/g, 'XX').replace('\x06', 'XX').length > RULE_W) throw new Error(`password: rule too long: ${t}`);
  // chunk tiles: every option a rule can deal
  const chunks = [...MONTHS, ...FRUITS, ...COFFEE, ...ANIMALS, ...VALUES, 'SYNERGY', 'Q1', 'Q2', 'Q3', 'Q4', word];
  const chunkId = (c) => {
    const i = chunks.indexOf(c);
    if (i < 0) throw new Error(`password: no chunk ${c}`);
    return i;
  };
  const out = ['; generated by c64/build.js (tools/mg/password.js) from src/minigames/password.js, src/data/mg-password.js'];
  out.push(`R_COUNT = ${RULES.length}`, `CHUNK_N = ${chunks.length}`, `BANDS = ${BANDS.length}`, `POLICIES = ${POLICIES}`);
  out.push(`QUIP_N = ${IT_QUIPS.length}`, `DONE_N = ${DONE_LINES.length}`, `TITLE_N = ${SCREEN_TITLES.length}`);
  out.push(`band_from: .byte ${BANDS.join(', ')}`);
  RULES.forEach(([id], i) => out.push(`R_${id.toUpperCase()} = ${i}`));
  table(out, 'rtext', texts, str);
  table(out, 'chunk', chunks, str);
  out.push(`dept_word: .byte ${str(word)}`);
  out.push(`roman_val: .byte ${ROMANS.map((r) => r[0]).join(', ')}`);
  table(out, 'roman', ROMANS.map((r) => r[1]), str);
  out.push(`; word lists for the rules (each 0-terminated, the list ends with an empty string)`);
  for (const [name, list] of [['l_months', MONTHS], ['l_fruits', FRUITS], ['l_coffee', COFFEE], ['l_animals', ANIMALS], ['l_values', VALUES]]) out.push(`${name}: .byte ${list.map(str).join(', ')}, 0`);
  // quips: "Almost! " is printed by the overlay in front of the first line (32 columns left)
  const quipLines = (q) => {
    const l1 = wrap(q, 32)[0];
    const l2 = q.slice(l1.length).trim();
    if (l2.length > 40) throw new Error(`password: quip too long: ${q}`);
    return [l1, l2];
  };
  table(out, 'quip', IT_QUIPS.map(quipLines), (l) => l.map(str).join(', '));
  table(out, 'doneln', DONE_LINES.map(two), (l) => l.map(str).join(', '));
  table(
    out,
    'stitle',
    SCREEN_TITLES.map((t) => (t.length <= 38 ? t : t.replace('IT SECURITY - ', 'IT - '))),
    (t) => {
      if (t.length > 38) throw new Error(`password: screen title too long: ${t}`);
      return str(t);
    },
  );
  // the policies
  const pols = [];
  BANDS.forEach((_, b) => {
    for (let p = 0; p < POLICIES; p++) {
      const rng = createRng(hashString(`password/${dept}/${b}/${p}`));
      const pol = generatePolicy({ d: BAND_D[b], rng, dept });
      const rules = pol.rules;
      // chunk tiles as create() deals them (addChunks), with the rule index that unlocks them
      const dealt = [];
      for (const [ri, r] of rules.entries()) {
        if (!r.options) continue;
        const count = r.tileCount ?? 1;
        if (!count) continue;
        const pick = pol.choice[r.id] || r.options[0];
        const others = rng.sample(r.options.filter((o) => o !== pick), count - 1);
        for (const t of rng.shuffle([pick, ...others])) if (!dealt.some((x) => x[1] === t)) dealt.push([ri, t]);
      }
      const num = (re, from) => Number((from?.text.match(re) || [0, 0])[1]);
      const [, minLen, maxLen] = rules[0].text.match(/Between (\d+) and (\d+)/).map(Number);
      const sum = rules.find((r) => r.id === 'sum')?.target ?? 0;
      const floor = num(/\((\d+)\)/, rules.find((r) => r.id === 'floor'));
      const quarter = num(/Q(\d)/, rules.find((r) => r.id === 'quarter'));
      const romanRule = rules.find((r) => r.id === 'roman');
      const roman = romanRule ? ROMANS.findIndex((x) => x[1] === romanRule.options[0]) : 0;
      for (const r of rules) if (!(r.id in ID)) throw new Error(`password: unknown rule ${r.id}`);
      if (pol.solution.length > 24) throw new Error('password: solution too long');
      ascii(pol.solution);
      pols.push({ rules, minLen, maxLen, sum, floor, quarter, roman, dealt, solution: pol.solution });
    }
  });
  // record: n, min, max, sum, floor, quarter, roman, rule ids, (rule index, chunk) pairs, $ff [, solution]
  // Test builds carry each policy's solution for the bot; to fit, they keep only the first BOT_POLICIES per band.
  const botSkip = (i) => i % POLICIES >= BOT_POLICIES;
  pols.forEach((p, i) => {
    const bytes = [p.rules.length, p.minLen, p.maxLen, p.sum, p.floor, p.quarter, p.roman, ...p.rules.map((r) => ID[r.id]), ...p.dealt.flatMap(([ri, t]) => [ri, chunkId(t)]), 255];
    if (botSkip(i)) out.push('.ifndef AUTOPLAY');
    out.push(`pol${i}: .byte ${bytes.join(', ')}`);
    out.push(botSkip(i) ? '.endif' : `.ifdef AUTOPLAY\n  .byte ${str(p.solution)}\n.endif`);
  });
  out.push(`.ifdef AUTOPLAY`, `POL_PICK = ${BOT_POLICIES}`, '.else', `POL_PICK = ${POLICIES}`, '.endif');
  const ref = (i) => (botSkip(i) ? `pol${i - (i % POLICIES)}` : `pol${i}`);
  out.push('.ifdef AUTOPLAY');
  out.push(`pol_lo: .byte ${pols.map((_, i) => `<${ref(i)}`).join(', ')}`);
  out.push(`pol_hi: .byte ${pols.map((_, i) => `>${ref(i)}`).join(', ')}`);
  out.push('.else');
  out.push(`pol_lo: .byte ${pols.map((_, i) => `<pol${i}`).join(', ')}`);
  out.push(`pol_hi: .byte ${pols.map((_, i) => `>pol${i}`).join(', ')}`);
  out.push('.endif');
  // partial score: 0.82 × (cleared / N)^1.15 × 255 for N 4-8, cleared 0..N-1
  const part = [];
  for (let n = 4; n <= 8; n++) for (let c = 0; c < 8; c++) part.push(c < n ? Math.round(0.82 * (c / n) ** 1.15 * 255) : 0);
  out.push(`partial: .byte ${part.join(', ')}  ; [N - 4][cleared]`);
  return out.join('\n') + '\n';
}
