// 360 Feedback content for the C64 overlay (src/mg_feedback.s), from src/data/mg-feedback.js and src/data/people.js:
// achievements and growth areas (the answers, wrapped in the option boxes at run time: 2 lines of OPT), the
// department's job titles, the names for a made-up colleague (the desk half without a floor quest), and the chat's
// line templates split around their {a} / {g}.
import { ACHIEVEMENTS, GROWTH_AREAS, BRAG_LINES, ADMIT_LINES, GREETINGS } from '../../../src/data/mg-feedback.js';
import { ROLES, FIRST_NAMES, LAST_NAMES } from '../../../src/data/people.js';
import { wrap } from '../mgdata.js';

const OPT = 16; // option box text: 2 lines of 16
const CHAT = 36; // chat page lines (the templates are wrapped at run time; the greeting must fit one line)

const ascii = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return s;
};
const str = (s) => `.byte "${ascii(s).replaceAll('"', '", 34, "')}", 0`;
const fits = (s) => {
  const l = wrap(s, OPT);
  if (l.length > 2 || l.some((x) => x.length > OPT)) throw new Error(`feedback: "${s}" does not fit an option box`);
};

function list(out, name, items, check = () => {}) {
  out.push(`N_${name.toUpperCase()} = ${items.length}`);
  items.forEach((s, i) => {
    check(s);
    out.push(`${name}${i}: ${str(s)}`);
  });
  out.push(`${name}_lo: .byte ${items.map((_, i) => `<${name}${i}`).join(', ')}`);
  out.push(`${name}_hi: .byte ${items.map((_, i) => `>${name}${i}`).join(', ')}`);
}

// "This quarter I {a}." -> prefix and suffix strings
function templates(out, name, items, key) {
  const parts = items.map((t) => {
    const i = t.indexOf(key);
    if (i < 0 || t.indexOf(key, i + 1) >= 0) throw new Error(`feedback: ${name} "${t}" needs one ${key}`);
    return [t.slice(0, i), t.slice(i + key.length)];
  });
  list(out, `${name}p`, parts.map((p) => p[0]));
  list(out, `${name}s`, parts.map((p) => p[1]));
}

export function dataAsm({ dept = 'lobby' } = {}) {
  const roles = ROLES[dept] || ROLES.lobby;
  if (roles.length < 4) throw new Error(`feedback: ${dept} needs 4 job titles`);
  for (const n of FIRST_NAMES) if (n.length > 8) throw new Error(`feedback: first name ${n} longer than 8`);
  for (const g of GREETINGS) if (g.length + 2 > CHAT) throw new Error(`feedback: greeting too long: ${g}`);
  const out = ['; generated by c64/build.js (tools/mg/feedback.js)'];
  list(out, 'ach', ACHIEVEMENTS, fits);
  list(out, 'grow', GROWTH_AREAS, fits);
  list(out, 'role', roles, fits);
  list(out, 'first', FIRST_NAMES);
  list(out, 'last', LAST_NAMES);
  list(out, 'greet', GREETINGS);
  templates(out, 'brag', BRAG_LINES, '{a}');
  templates(out, 'admit', ADMIT_LINES, '{g}');
  return out.join('\n') + '\n';
}
