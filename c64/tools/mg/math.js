// Expense Report (math) content for the C64 overlay (src/mg_math.s): the department's receipt items. The JS game
// keeps them as a module constant in src/minigames/math.js (not exported), so they are read from its source, like
// tools/mg/calendar.js does. Departments without their own list use `default`, as in the JS.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(import.meta.dir, '../../../src/minigames/math.js'), 'utf8');
const NAME_MAX = 13; // receipt card: name, a space and "$60" in 17 columns

const constant = (name) => {
  const at = SRC.indexOf(`const ${name} = `);
  if (at < 0) throw new Error(`math.js: no const ${name}`);
  return new Function(`return ${SRC.slice(at + name.length + 9, SRC.indexOf(';\n', at))}`)();
};

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const ITEMS = constant('ITEMS');
  const names = ITEMS[dept] || ITEMS.default;
  for (const n of names) if (n.length > NAME_MAX) throw new Error(`math: receipt item too long: ${n}`);
  if (names.length < 5) throw new Error(`math: ${dept} needs at least 5 items (5 receipts per report at d = 1)`);
  const out = ['; generated by c64/build.js (tools/mg/math.js) from src/minigames/math.js', `I_COUNT = ${names.length}`];
  names.forEach((s, i) => out.push(`it${i}: .byte ${str(s)}`));
  out.push(`item_lo: .byte ${names.map((_, i) => `<it${i}`).join(', ')}`);
  out.push(`item_hi: .byte ${names.map((_, i) => `>it${i}`).join(', ')}`);
  return out.join('\n') + '\n';
}
