// Lost Password data for the C64 overlay (src/mg_lostpw.s): pets (12 × 12 maps), names, the other boards' notes,
// first names for other people's pets. From src/data/mg-lostpw.js and src/data/people.js.
import { PETS, PET_NAMES, SPECIES_NAME, DECOY_BOARDS } from '../../../src/data/mg-lostpw.js';
import { FIRST_NAMES } from '../../../src/data/people.js';

// The pets' colours on the C64's eight hires colours (red stands in for brown, yellow for orange and gold).
const PET_C64 = { dog: [2, 7, 2, 0], cat: [7, 6, 0, 1], hamster: [7, 1, 2], fish: [7, 6, 4], parrot: [5, 2, 6], turtle: [5, 5, 5] };

const ascii = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return s;
};
const str = (s) => `.byte "${ascii(s).replaceAll('"', '", 34, "')}", 0`;
const table = (name, items) => [`${name}_lo: .byte ${items.map((l) => `<${l}`).join(', ')}`, `${name}_hi: .byte ${items.map((l) => `>${l}`).join(', ')}`];

export function dataAsm() {
  const species = Object.keys(PETS);
  const out = ['; generated by c64/build.js (tools/mg/lostpw.js)', `N_SPECIES = ${species.length}`, `N_NAMES = ${PET_NAMES.length}`, `N_NOTES = ${DECOY_BOARDS.length}`];
  species.forEach((sp, i) => {
    out.push(`spname${i}: ${str(SPECIES_NAME[sp])}`);
    out.push(`petmap${i}: .byte ${PETS[sp].map.map((r) => `"${r}"`).join(', ')}`);
    const c = PET_C64[sp];
    if (!c || c.length !== PETS[sp].colors.length) throw new Error(`lostpw: C64 colours for ${sp}`);
    out.push(`petcol${i}: .byte ${[...c, ...Array(4 - c.length).fill(c[0])].join(', ')}`);
  });
  out.push(...table('spname', species.map((_, i) => `spname${i}`)), ...table('petmap', species.map((_, i) => `petmap${i}`)));
  out.push(...table('petcol', species.map((_, i) => `petcol${i}`)));
  PET_NAMES.forEach((n, i) => out.push(`pname${i}: ${str(n)}`));
  out.push(...table('pname', PET_NAMES.map((_, i) => `pname${i}`)));
  DECOY_BOARDS.forEach((b, i) => out.push(`note${i}: .byte ${[b.title, ...b.lines].map((s) => `"${ascii(s).replaceAll('"', '", 34, "')}", 0`).join(', ')}`));
  out.push(...table('note', DECOY_BOARDS.map((_, i) => `note${i}`)));
  const owners = FIRST_NAMES.slice(0, 32);
  out.push(`N_OWNERS = ${owners.length}`);
  owners.forEach((n, i) => out.push(`owner${i}: ${str(n)}`));
  out.push(...table('owner', owners.map((_, i) => `owner${i}`)));
  out.push(boardSpritesAsm());
  return out.join('\n') + '\n';
}

// Two sprite frames of a mobile whiteboard (multicolour, 12 fat px × 21): '1' outline ($d025 black), '2' the board
// (sprite colour), '3' marker scribbles ($d026). Frame 0 has a "?" above it (not looked at yet), frame 1 a tick.
const BOARD = [
  '11111111111.',
  '12222222221.',
  '12332223221.',
  '12222222221.',
  '12333322221.',
  '12222223321.',
  '11111111111.',
  '..1.....1...',
  '..1.....1...',
  '..1.....1...',
  '.111...111..',
  '.1.1...1.1..',
];
const QMARK = ['....3333....', '...33..33...', '.......33...', '......33....', '.....33.....', '............', '.....33.....', '............', '............'];
const TICK = ['............', '..........1.', '.........11.', '........11..', '.1.....11...', '.11...11....', '..11.11.....', '...111......', '............'];

function spriteBytes(rows) {
  const out = new Uint8Array(64);
  const top = 21 - rows.length;
  rows.forEach((r, i) => {
    for (let x = 0; x < 12; x++) out[(top + i) * 3 + (x >> 2)] |= { '.': 0, 1: 1, 2: 2, 3: 3 }[r[x]] << (6 - (x & 3) * 2);
  });
  return out;
}

export function boardSpritesAsm() {
  return `board_sprites: .byte ${[...spriteBytes([...QMARK, ...BOARD]), ...spriteBytes([...TICK, ...BOARD])].join(', ')}\n`;
}
