// Inbox Triage content for the C64 overlay (build/gen/mg_inbox_data.s): the department's three bin labels and the
// items of each bin. The pools live in the game module itself (src/minigames/inbox.js, `const POOLS`, not
// exported), so they are read from its source; departments without a set of their own use `default`.
import { readFileSync } from 'node:fs';

const SRC = new URL('../../../src/minigames/inbox.js', import.meta.url);
const ITEM_W = 38; // the mail card: columns 1-38
const BIN_W = 10; // bin label inside a 12-wide box

function pools() {
  const src = readFileSync(SRC, 'utf8');
  const a = src.indexOf('const POOLS = ');
  const b = src.indexOf('\n};\n', a);
  if (a < 0 || b < 0) throw new Error('inbox: POOLS not found in src/minigames/inbox.js');
  return new Function(`return ${src.slice(a + 14, b + 2)}`)();
}

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  const parts = s.split('"').flatMap((p, i) => [...(i ? ['34'] : []), ...(p ? [`"${p}"`] : [])]);
  return [...parts, '0'].join(', ');
};

export function dataAsm({ dept }) {
  const all = pools();
  const pool = all[dept] || all.default;
  const out = ['; generated by c64/build.js from src/minigames/inbox.js POOLS (tools/mg/inbox.js)'];
  pool.bins.forEach((s, i) => {
    if (s.length > BIN_W) throw new Error(`inbox: bin label too long: ${s}`);
    out.push(`bin${i}: .byte ${str(s)}`);
  });
  out.push(`bin_lo: .byte ${pool.bins.map((_, i) => `<bin${i}`).join(', ')}`);
  out.push(`bin_hi: .byte ${pool.bins.map((_, i) => `>bin${i}`).join(', ')}`);
  const items = pool.items.flat();
  items.forEach((s, i) => {
    if (s.length > ITEM_W) throw new Error(`inbox: item too long for the card: ${s}`);
    out.push(`item${i}: .byte ${str(s)}`);
  });
  out.push(`item_lo: .byte ${items.map((_, i) => `<item${i}`).join(', ')}`);
  out.push(`item_hi: .byte ${items.map((_, i) => `>item${i}`).join(', ')}`);
  const first = [0, pool.items[0].length, pool.items[0].length + pool.items[1].length];
  out.push(`cat_first: .byte ${first.join(', ')}`);
  out.push(`cat_n: .byte ${pool.items.map((l) => l.length).join(', ')}`);
  return out.join('\n') + '\n';
}
