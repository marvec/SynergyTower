// Corporate Quiz content for the C64 overlay (src/mg_quiz.s): the department's question bank followed by the
// water-cooler small talk (src/data/mg-quiz.js), each as the question in up to 3 lines of 32, the right answer and
// its 3 wrong ones (up to 35 chars: the option boxes span the screen).
import { QUIZ } from '../../../src/data/mg-quiz.js';
import { wrap } from '../mgdata.js';

const LINE = 32;
const OPT = 35;

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const own = QUIZ[dept] || [];
  const all = [...own, ...QUIZ.general];
  if (own.length < 5) throw new Error(`quiz: ${dept} needs 5 questions (8 per game, 65 % from the department)`);
  const out = ['; generated by c64/build.js (tools/mg/quiz.js) from src/data/mg-quiz.js', `Q_DEPT = ${own.length}`, `Q_GEN = ${QUIZ.general.length}`];
  out.push(`quiz_lo: .byte ${all.map((_, i) => `<qz${i}`).join(', ')}`);
  out.push(`quiz_hi: .byte ${all.map((_, i) => `>qz${i}`).join(', ')}`);
  all.forEach((q, i) => {
    const lines = wrap(q.q, LINE);
    if (lines.length > 3) throw new Error(`quiz question too long: ${q.q}`);
    if (q.w.length !== 3) throw new Error(`quiz: 3 wrong answers expected: ${q.q}`);
    for (const s of [q.a, ...q.w]) if (s.length > OPT) throw new Error(`quiz answer too long: ${s}`);
    out.push(`qz${i}: .byte ${[lines[0], lines[1] || '', lines[2] || '', q.a, ...q.w].map(str).join(', ')}`);
  });
  return out.join('\n') + '\n';
}
