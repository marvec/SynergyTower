const BUBBLE_W = 22;
const OUTFITS = ['ladder', 'pizza', 'hivis', 'duck']; // outfit 1-4 in the overlay

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

