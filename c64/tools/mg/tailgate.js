const mirror = (rows) => rows.map((r) => [...r].reverse().join(''));

function spriteBytes(rows) {
  const out = new Array(64).fill(0);
  const top = 21 - rows.length;
  rows.forEach((r, i) => {
    if (r.length !== 12) throw new Error(`sprite row must be 12 wide: ${r}`);
    for (let x = 0; x < 12; x++) out[(top + i) * 3 + (x >> 2)] |= { '.': 0, 1: 1, 2: 2, 3: 3 }[r[x]] << (6 - (x & 3) * 2);
  });
  return out;
}

/** Bubble: .byte width, line 1, 0, line 2, 0. */
function bubble(s) {
  const lines = wrap(s, BUBBLE_W);
  if (lines.length > 2) throw new Error(`tailgate bubble too long: ${s}`);
  const w = Math.max(...lines.map((l) => l.length));
  return `.byte ${w}, ${str(lines[0])}, ${str(lines[1] || '')}`;
}

export function dataAsm({ dept = 'lobby' } = {}) {
  const sign = SIGNS[dept] || SIGNS.lobby;
  for (const s of sign) if (s.length > 36) throw new Error(`tailgate sign too long: ${s}`);
  // Bubble groups: excuses, then 3 lines per disguise, then the legit people's complaints.
  const groups = [
    ['EXCUSE', EXCUSES],
    ...OUTFITS.map((o) => [`DIS_${o.toUpperCase()}`, DISGUISE[o]]),
    ['LEGIT', LEGIT],
    ['LEGIT_VIS', LEGIT_VISITOR],
  ];
  const lines = [];
  const out = ['; generated by c64/build.js from src/data/mg-tailgate.js (tools/mg/tailgate.js)'];
  for (const [name, arr] of groups) {
    out.push(`B_${name} = ${lines.length}`, `N_${name} = ${arr.length}`);
    lines.push(...arr);
  }
  out.push(`B_COUNT = ${lines.length}`);
  out.push(`bub_lo: .byte ${lines.map((_, i) => `<bb${i}`).join(', ')}`);
  out.push(`bub_hi: .byte ${lines.map((_, i) => `>bb${i}`).join(', ')}`);
  lines.forEach((l, i) => out.push(`bb${i}: ${bubble(l)}`));
  // Floaters (one line, centred): WRONG, SNEAKED.
  for (const [name, arr] of [['WRONG', WRONG], ['SNEAK', SNEAKED]]) {
    out.push(`N_${name} = ${arr.length}`);
    arr.forEach((s, i) => {
      if (s.length > 38) throw new Error(`tailgate floater too long: ${s}`);
      out.push(`fl_${name.toLowerCase()}${i}: .byte ${str(s)}`);
    });
    out.push(`fl_${name.toLowerCase()}_lo: .byte ${arr.map((_, i) => `<fl_${name.toLowerCase()}${i}`).join(', ')}`);
    out.push(`fl_${name.toLowerCase()}_hi: .byte ${arr.map((_, i) => `>fl_${name.toLowerCase()}${i}`).join(', ')}`);
  }
  out.push(`s_sign1: .byte ${str(sign[0])}`, `s_sign2: .byte ${str(sign[1])}`);
  // Disguise frames for $e300: duck R/L, pizza R/L, ladder R/L.
  const frames = [DUCK, PIZZA, LADDER].flatMap((f) => [f, mirror(f)]);
  out.push('outfit_frames:');
  for (const f of frames) {
    const b = spriteBytes(f);
    for (let i = 0; i < 64; i += 16) out.push(`  .byte ${b.slice(i, i + 16).join(', ')}`);
  }
  return out.join('\n') + '\n';
}
