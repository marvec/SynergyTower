// Desk Plant Survival content for the C64 overlay (mg_plant.s), from src/data/mg-plant.js: the weekly captions
// (pre-wrapped for rows 22-23), the office events, and the plant itself: the browser game's stems and leaves
// (STEMS, stemPoint, drawLeaf in src/minigames/plant.js) rasterised to quarter-block chars at four droop levels.
import { CAPTIONS_GOOD, CAPTIONS_BAD, EVENTS } from '../../../src/data/mg-plant.js';
import { wrap } from '../mgdata.js';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const KINDS = ['ac', 'coffee', 'weekend', 'window', 'fruit', 'intern', 'heat', 'audit'];
export const PLANT_W = 11; // chars (2 × 2 quarter pixels each)
export const PLANT_H = 6;
const DROOPS = [0, 0.33, 0.67, 1];

const ascii = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return s;
};
// ca65 string bytes, 0-terminated (quotes as 34, no empty "" literals)
const str = (s) => [...ascii(s).split('"').flatMap((part, i) => [...(i ? ['34'] : []), ...(part ? [`"${part}"`] : [])]), '0'].join(', ');

function table(out, name, items, label, emit) {
  items.forEach((it, i) => out.push(`${label}${i}: ${emit(it)}`));
  out.push(`${name}_lo: .byte ${items.map((_, i) => `<${label}${i}`).join(', ')}`);
  out.push(`${name}_hi: .byte ${items.map((_, i) => `>${label}${i}`).join(', ')}`);
}

/** A caption in two lines: the first leaves room for the "W13: " prefix. */
function caption(text) {
  const words = wrap(text, 34);
  const l1 = words[0];
  const l2 = text.slice(l1.length).trim();
  if (l2.length > 40) throw new Error(`plant: caption too long: ${text}`);
  return [l1, l2];
}

// ---- the plant, as in plant.js (POT_X 240, POT_TOP 136)
const STEMS = [
  { a: -0.95, len: 56 },
  { a: -0.45, len: 78 },
  { a: 0.05, len: 92 },
  { a: 0.5, len: 76 },
  { a: 1.0, len: 54 },
];
const SX = 0.155; // browser px -> quarter pixels
const SY = 0.118;

function plantMap(dr) {
  const QW = PLANT_W * 2;
  const QH = PLANT_H * 2;
  const grid = Array.from({ length: QH }, () => Array(QW).fill(0));
  const set = (x, y) => {
    const qx = Math.round((x - 240) * SX + QW / 2 - 0.5);
    const qy = Math.floor((y - 136) * SY + QH);
    if (qx >= 0 && qx < QW && qy >= 0 && qy < QH) grid[qy][qx] = 1;
  };
  const stemPoint = (s, u) => {
    const side = Math.sign(s.a) || 1;
    const a = s.a * (1 + dr * 0.6);
    const L = s.len * (1 - dr * 0.15);
    return { x: 240 + Math.sin(a) * L * u + side * dr * 10 * u * u, y: 136 - Math.cos(a) * L * u + dr * 30 * u * u };
  };
  const leaf = (x, y, side, size) => {
    const tilt = Math.round(dr * 4);
    for (let i = 0; i < size; i++) {
      const thick = i < size / 2 ? 1 + Math.floor(i / 1.5) : Math.max(1, Math.floor((size - i) / 1.2));
      const lx = x + side * (i + 1);
      const ly = y - Math.round((size - i) * 0.3) + Math.round((i * tilt) / size);
      for (let k = 0; k <= thick; k++) set(lx, ly + k);
    }
  };
  STEMS.forEach((s, si) => {
    for (let k = 8; k <= 60; k++) {
      const p = stemPoint(s, k / 60);
      set(p.x, p.y);
    }
    [0.4, 0.68, 0.92].forEach((u, li) => {
      const p = stemPoint(s, u);
      leaf(p.x, p.y, (li + si) % 2 ? 1 : -1, 8 + li * 2);
    });
    const tip = stemPoint(s, 1);
    leaf(tip.x, tip.y - 2, Math.sign(s.a) || 1, 10);
  });
  const cells = [];
  for (let cy = 0; cy < PLANT_H; cy++)
    for (let cx = 0; cx < PLANT_W; cx++) {
      const g = (dx, dy) => grid[cy * 2 + dy][cx * 2 + dx];
      const p = g(0, 0) | (g(1, 0) << 1) | (g(0, 1) << 2) | (g(1, 1) << 3);
      cells.push(p ? 240 + p : 32);
    }
  return cells;
}

/** ASCII preview for checking the shapes: `bun -e "import('./tools/mg/plant.js').then(m => m.preview())"`. */
export function preview() {
  for (const dr of DROOPS) {
    const m = plantMap(dr);
    const rows = [];
    for (let y = 0; y < PLANT_H * 2; y++) {
      let r = '';
      for (let x = 0; x < PLANT_W * 2; x++) {
        const c = m[(y >> 1) * PLANT_W + (x >> 1)];
        const bit = 1 << ((x & 1) + (y & 1) * 2);
        r += c !== 32 && (c - 240) & bit ? '#' : '.';
      }
      rows.push(r);
    }
    console.log(`droop ${dr}\n${rows.join('\n')}\n`);
  }
}

/** The motivational poster's word for the department (POSTER in plant.js, which doesn't export it). */
function posterWord(dept) {
  const src = readFileSync(fileURLToPath(new URL('../../../src/minigames/plant.js', import.meta.url)), 'utf8');
  const at = src.indexOf('const POSTER = ');
  const POSTER = new Function(`return ${src.slice(at + 15, src.indexOf(';\n', at))}`)();
  const w = POSTER[dept] || 'GROWTH';
  if (w.length > 8) throw new Error(`plant: poster word too long: ${w}`);
  return w;
}

export function dataAsm({ dept = 'lobby' } = {}) {
  const out = ['; generated by c64/build.js from src/data/mg-plant.js (tools/mg/plant.js)'];
  const word = posterWord(dept);
  out.push(`poster_word: .byte ${str(word)}`, `POSTER_X = ${2 + Math.floor((8 - word.length) / 2)}`);
  out.push(`PLANT_W = ${PLANT_W}`, `PLANT_H = ${PLANT_H}`, `DROOPS = ${DROOPS.length}`);
  out.push('plant_maps:');
  for (const dr of DROOPS) out.push(`  .byte ${plantMap(dr).join(', ')}`);
  out.push(`CG_COUNT = ${CAPTIONS_GOOD.length}`, `CB_COUNT = ${CAPTIONS_BAD.length}`);
  table(out, 'capg', CAPTIONS_GOOD, 'cg', (c) => `.byte ${caption(c).map(str).join(', ')}`);
  table(out, 'capb', CAPTIONS_BAD, 'cb', (c) => `.byte ${caption(c).map(str).join(', ')}`);
  out.push(`cap_first: .byte ${caption('Plant onboarded. Badge pending.').map(str).join(', ')}`);
  out.push(`cap_last: .byte ${caption('Quarter close! Hold on...').map(str).join(', ')}`);
  out.push(`EV_COUNT = ${EVENTS.length}`);
  for (const e of EVENTS) {
    if (!KINDS.includes(e.kind)) throw new Error(`plant: unknown event ${e.kind}`);
    for (const s of [e.text, e.sub]) if (s.length > 40) throw new Error(`plant: event text too long: ${s}`);
  }
  out.push(`ev_kind: .byte ${EVENTS.map((e) => KINDS.indexOf(e.kind)).join(', ')}`);
  table(out, 'ev', EVENTS, 'ev', (e) => `.byte ${str(e.text)}, ${str(e.sub)}`);
  return out.join('\n') + '\n';
}
