// Meeting Survival content for the C64 overlay (src/mg_meeting.s), from src/data/mg-meeting.js: every buzzword
// and filler line (common to all departments), each wrapped to two lines of the speech bubble and byte-pair
// encoded (tools/bpe.js, its own table: bpe_a / bpe_b; the overlay expands a line when the boss starts it), the
// department's boss and whiteboard scribbles, and the reaction pools.
import { BUZZ, FILLER, BOSS, BOARD, GOOD_NOD, BAD_NOD, ASLEEP } from '../../../src/data/mg-meeting.js';
import { wrap } from '../mgdata.js';
import { trainBpe, encodeBpe } from '../bpe.js';

const LINE = 36; // bubble text width (the box spans the screen)
const MSG = 30; // reactions under the bubble (row 6, right of the tail)
const SAY = 36; // the boss's interjections, in the bubble
const NAME = 18; // the boss's name under him
const BOARD_W = 10; // the whiteboard's left half

const str = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};
const fit = (s, n) => {
  if (s.length > n) throw new Error(`meeting: "${s}" is longer than ${n}`);
  return str(s);
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const lines = [...BUZZ, ...FILLER];
  const out = ['; generated by c64/build.js (tools/mg/meeting.js) from src/data/mg-meeting.js', `B_COUNT = ${BUZZ.length}`, `F_COUNT = ${FILLER.length}`];
  if (BUZZ.length > 255 || FILLER.length > 255) throw new Error('meeting: too many lines');
  out.push(`line_lo: .byte ${lines.map((_, i) => `<ln${i}`).join(', ')}`);
  out.push(`line_hi: .byte ${lines.map((_, i) => `>ln${i}`).join(', ')}`);
  const halves = lines.flatMap((s) => {
    const w = wrap(s, LINE);
    if (w.length > 2) throw new Error(`meeting: more than 2 lines: ${s}`);
    for (const h of w) if (/[^\x20-\x7e]/.test(h)) throw new Error(`no C64 glyph in "${h}"`);
    return [w[0], w[1] || ''].map((h) => [...h].map((c) => c.charCodeAt(0)));
  });
  const pairs = trainBpe(halves, 128);
  out.push(`bpe_a: .byte ${pairs.map((p) => p[0]).join(', ')}`);
  out.push(`bpe_b: .byte ${pairs.map((p) => p[1]).join(', ')}`);
  lines.forEach((_, i) => out.push(`ln${i}: .byte ${[...encodeBpe(halves[2 * i], pairs), 0, ...encodeBpe(halves[2 * i + 1], pairs), 0].join(', ')}`));
  const pool = (name, list, n) => {
    out.push(`${name.toUpperCase()}_N = ${list.length}`);
    out.push(`${name}_lo: .byte ${list.map((_, i) => `<${name}${i}`).join(', ')}`);
    out.push(`${name}_hi: .byte ${list.map((_, i) => `>${name}${i}`).join(', ')}`);
    list.forEach((s, i) => out.push(`${name}${i}: .byte ${fit(s, n)}`));
  };
  pool('goodnod', GOOD_NOD, MSG);
  pool('badnod', BAD_NOD, SAY);
  pool('asleep', ASLEEP, SAY);
  const board = BOARD[dept] || ['SYNERGY', 'Q4 GOALS'];
  out.push(`s_boss: .byte ${fit(BOSS[dept] || 'The Boss', NAME)}`);
  out.push(`s_board1: .byte ${fit(board[0], BOARD_W)}`);
  out.push(`s_board2: .byte ${fit(board[1], BOARD_W)}`);
  return out.join('\n') + '\n';
}
