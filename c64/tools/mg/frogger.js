// Coffee Crossing (src/minigames/frogger.js) content for the C64 overlay: the floater and speech-bubble lines
// (read from the module's source, where they are local constants), the department note, and the traffic
// sprites that the person frames don't cover (+ the dog and its stride table).
import { readFileSync } from 'node:fs';

const SRC = readFileSync(new URL('../../../src/minigames/frogger.js', import.meta.url), 'utf8');

/** A `const NAME = [...]` / `{...}` literal from the module's source. */
function literal(name) {
  const at = SRC.indexOf(`const ${name} = `);
  if (at < 0) throw new Error(`frogger.js: no ${name}`);
  const open = SRC.indexOf(' = ', at) + 3;
  const close = SRC.indexOf(SRC[open] === '[' ? '];' : '};', open) + 1;
  return new Function(`return ${SRC.slice(open, close)}`)();
}

const str = (s, max) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  if (s.length > max) throw new Error(`frogger line too long for the C64 screen: "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

