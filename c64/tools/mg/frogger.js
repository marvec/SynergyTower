function spriteBytes(rows) {
  const out = new Array(64).fill(0);
  const top = 21 - rows.length;
  rows.forEach((r, i) => {
    if (r.length !== 12) throw new Error(`frogger sprite row is not 12 px: "${r}"`);
    for (let x = 0; x < 12; x++) out[(top + i) * 3 + (x >> 2)] |= { '.': 0, 1: 1, 2: 2, 3: 3 }[r[x]] << (6 - (x & 3) * 2);
  });
  return out;
}

export function dataAsm({ dept = 'lobby' } = {}) {
  const pools = [
    ['QQ', literal('QQ_LINES'), 34],
    ['BYE', literal('QQ_BYE'), 38],
    ['SPILL', literal('SPILL'), 38],
    ['BUMP', literal('DESK_BUMP'), 38],
    ['DELIV', literal('DELIVERED'), 23], // after "100% delivered! "
  ];
  const note = literal('DEPT_NOTE')[dept] || 'Mind the traffic.';
  const out = ['; generated by c64/build.js (tools/mg/frogger.js) from src/minigames/frogger.js'];
  const all = [];
  for (const [name, lines, max] of pools) {
    out.push(`${name}_0 = ${all.length}`, `${name}_N = ${lines.length}`);
    for (const s of lines) all.push(str(s, max));
  }
  out.push(`str_lo: .byte ${all.map((_, i) => `<fs${i}`).join(', ')}`);
  out.push(`str_hi: .byte ${all.map((_, i) => `>fs${i}`).join(', ')}`);
  all.forEach((s, i) => out.push(`fs${i}: .byte ${s}`));
  out.push(`s_note: .byte ${str(note, 38)}`);
  out.push('frog_frames:');
  for (const k of ORDER) out.push(`  .byte ${spriteBytes(FRAMES[k]).join(', ')} ; ${k}`);
  out.push(`dog_frame: .byte ${spriteBytes(DOG).join(', ')}`);
  // The dog's speed factor over its stride (JS: 1 + 0.55 sin(3 t + phase)), × 128, 64 steps per cycle.
  out.push(`dog_sin: .byte ${Array.from({ length: 64 }, (_, i) => 128 + Math.round(70 * Math.sin((2 * Math.PI * i) / 64))).join(', ')}`);
  return out.join('\n') + '\n';
}
