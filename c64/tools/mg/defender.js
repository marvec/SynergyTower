// Calendar Defender (src/minigames/defender.js) content for the C64 overlay: the invite labels by kind (the
// department's own ones join the standard pool, as in the browser), and the floater lines. Labels are drawn
// clipped to the invite's width on screen (3-6 characters), so long ones show their start. Also two curve tables.
import { INVITES, INVITES_DEPT, KILL_LINES, LEAK_LINES } from '../../../src/data/mg-defender.js';

const KINDS = ['short', 'std', 'long', 'recur', 'mini', 'boss']; // K_* order in the overlay
const LABEL_MAX = 24;
const LINE_MAX = 38;

const str = (s, max) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  if (s.length > max) throw new Error(`defender line too long: "${s}"`);
  return `"${s.replaceAll('"', '", 34, "')}", 0`;
};

export function dataAsm({ dept = 'lobby' } = {}) {
  const pools = KINDS.map((k) => (k === 'std' ? [...INVITES.std, ...(INVITES_DEPT[dept] || [])] : INVITES[k]));
  const all = [];
  const out = ['; generated by c64/build.js (tools/mg/defender.js) from src/data/mg-defender.js'];
  out.push(`pool_first: .byte ${pools.map((p, i) => pools.slice(0, i).reduce((n, q) => n + q.length, 0)).join(', ')}`);
  out.push(`pool_n: .byte ${pools.map((p) => p.length).join(', ')}`);
  for (const p of pools) for (const s of p) all.push(str(s, LABEL_MAX));
  out.push(`KILL_0 = ${all.length}`, `KILL_N = ${KILL_LINES.length}`);
  for (const s of KILL_LINES) all.push(str(s, LINE_MAX));
  out.push(`LEAK_0 = ${all.length}`, `LEAK_N = ${LEAK_LINES.length}`);
  for (const s of LEAK_LINES) all.push(str(s, LINE_MAX));
  if (all.length > 255) throw new Error('defender: too many strings');
  out.push(`str_lo: .byte ${all.map((_, i) => `<ds${i}`).join(', ')}`);
  out.push(`str_hi: .byte ${all.map((_, i) => `>ds${i}`).join(', ')}`);
  all.forEach((s, i) => out.push(`ds${i}: .byte ${s}`));
  // Curves of the difficulty and the wave schedule: hpMul = 1 + 1.3 d^0.7 (× 64, by A / 16), f^0.85 (× 256, by f × 32).
  out.push(`hpmul_tab: .byte ${Array.from({ length: 17 }, (_, i) => Math.round(64 * (1 + 1.3 * Math.pow(Math.min(1, i / 15.9375), 0.7)))).join(', ')}`);
  out.push(`pow85_tab: .byte ${Array.from({ length: 32 }, (_, i) => Math.min(255, Math.round(256 * Math.pow(i / 32, 0.85)))).join(', ')}`);
  return out.join('\n') + '\n';
}
