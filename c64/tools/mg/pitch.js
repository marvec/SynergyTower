// Elevator Pitch content for the C64 overlay (mg_pitch.s), from src/data/mg-pitch.js: the reel words with their
// category and hidden appeal, the rumours (wrapped for rows 2-3), the CEO's lines (wrapped for the speech bubble),
// the x^1.3 score curve, and the sprites (you, the CEO with four faces, the CEO's grey hair + collar).
import { MOODS, SLOTS, REPLIES, ARRIVALS, INTROS, REACTIONS, NEXTS, MOOD_BONUS } from '../../../src/data/mg-pitch.js';
import { wrap } from '../mgdata.js';

const CATS = ['animals', 'ai', 'space', 'green', 'money', 'boring', 'buzz']; // the six moods first, then buzz
const BUBBLE_W = 14; // speech bubble: 14 columns × 4 rows
const BUBBLE_H = 4;
const RUMOUR_W = 36; // row 2 after the icon; row 3 leaves room for "CEO likes" + icon
const RUMOUR_W2 = 23;
const R_PER = 3; // rumours kept per mood, replies kept per verdict band (the 8 KB overlay)
const REPLY_PER = 4;

const ascii = (s) => {
  if (/[^\x20-\x7e]/.test(s)) throw new Error(`no C64 glyph in "${s}"`);
  return s;
};
// ca65 string bytes, 0-terminated (quotes as 34, no empty "" literals)
const str = (s) => [...ascii(s).split('"').flatMap((part, i) => [...(i ? ['34'] : []), ...(part ? [`"${part}"`] : [])]), '0'].join(', ');

/** A speech-bubble text: line count, then the lines (0-terminated). */
function bubble(s) {
  const lines = wrap(s, BUBBLE_W);
  if (lines.length > BUBBLE_H || lines.some((l) => l.length > BUBBLE_W)) throw new Error(`pitch: too long for the bubble: ${s}`);
  return `.byte ${lines.length}, ${lines.map(str).join(', ')}`;
}

function table(out, name, items, label, emit) {
  items.forEach((it, i) => out.push(`${label}${i}: ${emit(it)}`));
  out.push(`${name}_lo: .byte ${items.map((_, i) => `<${label}${i}`).join(', ')}`);
  out.push(`${name}_hi: .byte ${items.map((_, i) => `>${label}${i}`).join(', ')}`);
}

// ---- sprites: 12 fat px × 21 rows, '1' = $d025 black, '2' = sprite colour, '3' = $d026 skin
const LEGS = ['..111..111..', '..111..111..', '..111..111..', '..111..111..', '..111..111..', '.1111..1111.'];
const YOU = [
  '...111111...', '..11111111..', '..13333331..', '.3331331333.', '..33333333..', '..33311333..', '...333333...',
  '..22233222..', '.2222222222.', '.2222222222.', '.2222222222.', '.2222222222.', '.2222222222.', '.3222222223.',
  '..11111111..', ...LEGS,
];
const CEO_BODY = ['..11122111..', '.1111221111.', '.1111221111.', '.1111221111.', '.1111111111.', '.3111111113.', '..11111111..', ...LEGS];
const CEO_TOP = ['...333333...', '..33333333..'];
const FACES = {
  neutral: ['..33333333..', '.3331331333.', '..33333333..', '..33311333..', '...333333...'],
  delighted: ['..33133133..', '.3323333233.', '..31333313..', '..33111133..', '...333333...'],
  bored: ['..33333333..', '.3311331133.', '..33333333..', '..33333113..', '...333333...'],
  annoyed: ['..31333313..', '.3331331333.', '..23333332..', '..33111133..', '...313313...'],
};
// Overlay sprite in the same grid ('#' = its own colour, light grey): side hair and the white collar.
const CEO_OVER = ['............', '..#......#..', '..#......#..', '..#......#..', '............', '............', '............', '...##..##...'];

function spriteBytes(rows, over = false) {
  if (rows.length !== 21 || rows.some((r) => r.length !== 12)) throw new Error('pitch: sprite must be 12 × 21');
  const out = new Array(64).fill(0);
  rows.forEach((r, y) => {
    for (let x = 0; x < 12; x++) {
      const v = over ? (r[x] === '#' ? 2 : 0) : { '.': 0, 1: 1, 2: 2, 3: 3 }[r[x]];
      out[y * 3 + (x >> 2)] |= v << (6 - (x & 3) * 2);
    }
  });
  return out;
}

export function sprites() {
  const ceo = (face) => [...CEO_TOP, ...face, '.....33.....', ...CEO_BODY];
  const frames = [YOU, ceo(FACES.neutral), ceo(FACES.delighted), ceo(FACES.bored), ceo(FACES.annoyed)].map((f) => spriteBytes(f));
  frames.push(spriteBytes([...CEO_OVER, ...Array(13).fill('............')], true));
  return frames;
}

export function dataAsm({ dept = 'lobby' } = {}) {
  const out = ['; generated by c64/build.js from src/data/mg-pitch.js (tools/mg/pitch.js)'];
  out.push(`MOOD_BONUS = ${MOOD_BONUS}`, `CAT_BUZZ = ${CATS.indexOf('buzz')}`, `CAT_BORING = ${CATS.indexOf('boring')}`);

  // reel words, slot by slot
  const words = [];
  const first = [];
  for (const s of SLOTS) {
    first.push(words.length);
    for (const w of s.words) {
      if (w.w.length > 14) throw new Error(`pitch: reel word too long: ${w.w}`);
      words.push(w);
    }
  }
  if (words.length > 255) throw new Error('pitch: too many words');
  out.push(`W_COUNT = ${words.length}`);
  out.push(`slot_first: .byte ${first.join(', ')}, ${words.length}`);
  SLOTS.forEach((s, i) => out.push(`sl${i}: .byte ${str(s.label)}`));
  out.push(`slot_lo: .byte ${SLOTS.map((_, i) => `<sl${i}`).join(', ')}`, `slot_hi: .byte ${SLOTS.map((_, i) => `>sl${i}`).join(', ')}`);
  out.push(`w_cat: .byte ${words.map((w) => CATS.indexOf(w.cat)).join(', ')}`);
  out.push(`w_base: .byte ${words.map((w) => w.base).join(', ')}`);
  table(out, 'w', words, 'wd', (w) => `.byte ${str(w.w)}`);

  // rumours: 5 per mood, two lines each
  const rumours = [];
  for (const cat of CATS.slice(0, 6)) {
    const list = MOODS[cat].rumours.slice(0, R_PER);
    if (list.length !== R_PER) throw new Error(`pitch: expected ${R_PER} rumours for ${cat}`);
    for (const r of list) {
      const [l1, ...rest] = wrap(`Rumour: ${r}`, RUMOUR_W);
      const l2 = rest.join(' ');
      if (l2.length > RUMOUR_W2) throw new Error(`pitch: rumour too long: ${r}`);
      rumours.push([l1, l2]);
    }
  }
  out.push(`R_PER = ${R_PER}`);
  table(out, 'rum', rumours, 'ru', (r) => `.byte ${r.map(str).join(', ')}`);

  // the CEO's lines
  out.push(`intro: ${bubble(INTROS[dept] || 'You have until my floor. Go.')}`);
  const bands = ['great', 'good', 'meh', 'bad'];
  const replies = bands.flatMap((b) => REPLIES[b].slice(0, REPLY_PER));
  out.push(`REPLY_PER = ${REPLY_PER}`);
  table(out, 'rep', replies, 'rp', bubble);
  out.push(`ARRIVE_COUNT = ${ARRIVALS.length}`);
  table(out, 'arr', ARRIVALS, 'ar', bubble);
  out.push(`NEXT_COUNT = ${NEXTS.length}`);
  table(out, 'nxt', NEXTS, 'nx', bubble);
  // reactions: high, mid, low (in the bubble), stall (over the player)
  const rbands = ['high', 'mid', 'low', 'stall'];
  const reacts = rbands.flatMap((b) => REACTIONS[b]);
  out.push(`react_first: .byte ${rbands.map((b) => rbands.slice(0, rbands.indexOf(b)).reduce((n, x) => n + REACTIONS[x].length, 0)).join(', ')}`);
  out.push(`react_count: .byte ${rbands.map((b) => REACTIONS[b].length).join(', ')}`);
  table(out, 'rea', reacts, 're', bubble);

  // score curve in 64 steps: raw 0..255 (index raw / 4) -> 255 × (raw / 255) ^ 1.3, the last step = 255
  const curve = Array.from({ length: 64 }, (_, i) => Math.round(255 * Math.pow(i / 63, 1.3)));
  for (let i = 0; i < 64; i += 32) out.push(`${i ? '' : 'curve:'} .byte ${curve.slice(i, i + 32).join(', ')}`);

  out.push('sprite_data:');
  for (const f of sprites()) out.push(`  .byte ${f.join(', ')}`);
  return out.join('\n') + '\n';
}
