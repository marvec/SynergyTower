export const LINE_H = 10;
const GLYPH_H = 8;
const glyphs = new Map();
for (const [ch, def] of Object.entries(G)) {
  const rows = def.split('|');
  glyphs.set(ch, { w: rows[0].length, rows });
}
const fallback = glyphs.get('?');

let atlasCache = new Map();
let layout = null;

function buildLayout() {
  let x = 0;
  layout = new Map();
  for (const [ch, gl] of glyphs) {
    layout.set(ch, { x, w: gl.w, rows: gl.rows });
    x += gl.w + 1;
  }
  layout.width = x;
}

function atlasFor(color) {
  if (!layout) buildLayout();
  let c = atlasCache.get(color);
  if (c) return c;
  c = document.createElement('canvas');
  c.width = layout.width;
  c.height = GLYPH_H;
  const g = c.getContext('2d');
  g.fillStyle = color;
  for (const [, gl] of layout) {
    gl.rows.forEach((row, y) => {
      for (let i = 0; i < row.length; i++) if (row[i] === '#') g.fillRect(gl.x + i, y, 1, 1);
    });
  }
  atlasCache.set(color, c);
  return c;
}

export function charWidth(ch) {
  return (glyphs.get(ch) || fallback).w;
}

export function measureText(str, scale = 1) {
  let w = 0;
  for (const ch of str) w += charWidth(ch) + 1;
  return Math.max(0, w - 1) * scale;
}

/**
 * Draw text. opts: color, scale, align ('left'|'center'|'right'), shadow (colour or false).
 * Returns the drawn width.
 */
export function drawText(g, str, x, y, opts = {}) {
  str = String(str);
  const { color = '#fff', scale = 1, align = 'left', shadow = null } = opts;
  const w = measureText(str, scale);
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const cy = Math.round(y);
  if (shadow) drawRun(g, str, cx + scale, cy + scale, shadow, scale);
  drawRun(g, str, cx, cy, color, scale);
  return w;
}

function drawRun(g, str, x, y, color, scale) {
  const atlas = atlasFor(color);
  for (const ch of str) {
    const gl = layout.get(ch) || layout.get('?');
    g.drawImage(atlas, gl.x, 0, gl.w, GLYPH_H, x, y, gl.w * scale, GLYPH_H * scale);
    x += (gl.w + 1) * scale;
  }
}

/** Greedy word wrap into lines no wider than maxWidth. Honors '\n'. */
export function wrapText(str, maxWidth, scale = 1) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? line + ' ' + word : word;
      if (measureText(test, scale) <= maxWidth || !line) line = test;
      else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}

export function drawWrapped(g, str, x, y, maxWidth, opts = {}) {
  const scale = opts.scale || 1;
  const lh = (opts.lineHeight || LINE_H) * scale;
  const lines = wrapText(str, maxWidth, scale);
  lines.forEach((l, i) => drawText(g, l, x, y + i * lh, opts));
  return lines.length * lh;
}

export const hasGlyph = (ch) => glyphs.has(ch);
